"""The agent guide: one page that says how to use bngsim, in the wheel (issue #1699).

An agent that has not met bngsim learns it from what it can read during the
task. ``agent_guide.md``, next to this module, is that text: rules and runnable
recipes rather than narrative, small enough to be read whole. It ships in the
wheel, so :func:`agent_guide` returns the guide of the version that is
installed, with no network, and the documentation includes the same file.

Its translation table, from other tools' calls to bngsim's, is generated from
:data:`bngsim._foreign_names.FOREIGN_NAMES`, the table bngsim's wrong-name
errors read, so the two cannot say different things. It sits between two
markers in the file; ``python scripts/agent_guide_table.py`` regenerates it,
and ``test_agent_guide.py`` fails while the file holds anything else.
"""

from __future__ import annotations

from importlib import resources

from bngsim._foreign_names import FOREIGN_NAMES, ForeignName

#: The guide's file name, in the bngsim package.
GUIDE_FILE = "agent_guide.md"

#: The markers the generated translation table sits between.
TABLE_START = "<!-- translation-table: generated from bngsim._foreign_names; do not edit -->"
TABLE_END = "<!-- end of translation-table -->"

#: The tools the table translates from, in the order it lists them. A row of
#: FOREIGN_NAMES from another origin (``"guess"``, ``"bngsim"``) is a wrong
#: name bngsim's errors answer, not a habit of a tool, and is left out.
TOOLS = (
    "libRoadRunner",
    "Tellurium",
    "AMICI",
    "COPASI (basico)",
    "BNGL actions",
    "PySB",
    "SciPy",
    "pandas",
)

#: The owners whose rows the table shows. The other ``Simulator.<method>``
#: owners repeat ``Simulator.run``'s keywords for one run call each, and the
#: error that call raises says so.
_SHOWN_OWNERS = (
    "bngsim",
    "Model",
    "Simulator",
    "Result",
    "Simulator.run",
    "pattern",
    "translation",
)

#: The text :func:`agent_guide` puts before the guide for ``skill=True``. A
#: skill is the file several agent harnesses load when a task matches its
#: description: YAML front matter, then the instructions.
SKILL_HEADER = """\
---
name: bngsim
description: >-
  Simulate biochemical reaction networks with the bngsim Python package:
  load BioNetGen (.net, .bngl), SBML or Antimony models, run ODE or
  stochastic (SSA, PSA, network-free) simulations, scan parameters, find
  steady states and compute parameter sensitivities. Use when a task loads,
  simulates or fits a model with bngsim, or asks for a BioNetGen, SBML or
  Antimony model to be simulated in Python.
---

<!-- Generated by `python -m bngsim skill` from the agent guide of the
installed bngsim; regenerate it after an upgrade rather than editing it. -->

"""


def _foreign_call(entry: ForeignName) -> str:
    """What the caller writes, as code, for one row."""
    if entry.owner in ("pattern", "translation"):
        return entry.name
    if entry.owner == "bngsim":
        return f"bngsim.{entry.name}"
    if entry.owner == "Simulator.run":
        return f"sim.run({entry.name}=...)"
    return f"{dict(Model='model', Simulator='sim', Result='result')[entry.owner]}.{entry.name}"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def translation_table() -> str:
    """The guide's translation table, as Markdown, from ``FOREIGN_NAMES``."""
    by_tool: dict[str, list[ForeignName]] = {tool: [] for tool in TOOLS}
    for entry in FOREIGN_NAMES:
        if entry.owner in _SHOWN_OWNERS and entry.origin in by_tool:
            by_tool[entry.origin].append(entry)
    lines: list[str] = []
    for tool, entries in by_tool.items():
        if not entries:
            continue
        lines += [f"**{tool}**", "", "| you write | in BNGsim | note |", "|---|---|---|"]
        for e in entries:
            use = f"`{_cell(e.use)}`" if e.use else "—"
            lines.append(f"| `{_cell(_foreign_call(e))}` | {use} | {_cell(e.note)} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def _stored_guide() -> str:
    return resources.files("bngsim").joinpath(GUIDE_FILE).read_text(encoding="utf-8")


def _with_table(text: str, table: str) -> str:
    start, end = text.index(TABLE_START), text.index(TABLE_END)
    return text[: start + len(TABLE_START)] + "\n\n" + table + "\n" + text[end:]


def agent_guide(*, skill: bool = False) -> str:
    """The BNGsim agent guide: how to use this library, in one page.

    Rules and runnable recipes written for an AI agent, or anyone, meeting
    bngsim for the first time: the dozen calls that load, run, read and change
    a model; the rules that otherwise cause wrong answers; what a refusal
    means; what each feature needs installed; a translation table from
    libRoadRunner, Tellurium, AMICI, COPASI, BNGL actions and PySB; how to check
    a result; and how to report a bug. It is the guide of the installed
    version, read from the package, with no network.

    ``python -m bngsim guide`` prints it. The documentation carries the same
    page, with the user guides and an ``llms.txt`` index beside it, at
    https://bngsim.readthedocs.io.

    Parameters
    ----------
    skill : bool, optional
        Put a skill header before the guide: YAML front matter naming bngsim
        and saying when to use it, the form several agent harnesses load as a
        ``SKILL.md`` file. ``python -m bngsim skill`` prints this form.

    Returns
    -------
    str
        The guide, as Markdown.

    Examples
    --------
    >>> import bngsim
    >>> bngsim.agent_guide().splitlines()[0]
    '# BNGsim agent guide'
    """
    text = _stored_guide()
    return SKILL_HEADER + text if skill else text
